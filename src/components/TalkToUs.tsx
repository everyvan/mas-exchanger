import { useState, useMemo } from 'react';
import { DiscussionEmbed, CommentCount } from 'disqus-react';
import { MessageSquare, MessagesSquare, Sparkles, Shield, Info, ExternalLink, HelpCircle, CheckCircle2 } from 'lucide-react';

interface ArticleConfig {
  id: string;
  title: string;
  url: string;
}

export function TalkToUs() {
  // Available discussion topics
  const topics: { id: string; title: string; subtitle: string; icon: string }[] = [
    {
      id: 'singarate-talk-to-us-main',
      title: 'General Exchange Rate & Community Discussion',
      subtitle: 'Share rate queries, cross-border remittance questions, and community thoughts',
      icon: '🇸🇬',
    },
    {
      id: 'singarate-money-changers-jb',
      title: 'Causeway Travel & Money Changer Rates',
      subtitle: 'The Arcade (Raffles Place), People\'s Park (Chinatown), and Johor Bahru tips',
      icon: '🚗',
    },
    {
      id: 'singarate-mas-api-feedback',
      title: 'MAS API & Feature Requests',
      subtitle: 'Suggest features, technical improvements, and developer integration ideas',
      icon: '💡',
    },
  ];

  const [selectedTopicId, setSelectedTopicId] = useState<string>(topics[0].id);
  const [useSsoConfig, setUseSsoConfig] = useState<boolean>(false);

  // Active topic article properties
  const activeTopic = useMemo(() => {
    return topics.find((t) => t.id === selectedTopicId) || topics[0];
  }, [selectedTopicId]);

  // Construct current URL safely
  const currentOrigin = typeof window !== 'undefined' ? window.location.origin : 'https://singarate.app';
  const article: ArticleConfig = useMemo(() => {
    return {
      id: activeTopic.id,
      title: `${activeTopic.title} - SingaRate`,
      url: `${currentOrigin}/#talk-to-us?topic=${activeTopic.id}`,
    };
  }, [activeTopic, currentOrigin]);

  // Disqus shortname provided by user
  const disqusShortname = 'itdoesntmatter-2';

  // Standard config
  const standardConfig = useMemo(() => {
    return {
      url: article.url,
      identifier: article.id,
      title: article.title,
      language: 'en',
    };
  }, [article]);

  // SSO-enabled config matching user snippet 3
  const ssoConfig = useMemo(() => {
    return {
      url: article.url,
      identifier: article.id,
      title: article.title,
      language: 'en',
      remoteAuthS3: '', // Generated by your server (see https://help.disqus.com/customer/en/articles/1717160-integrating-single-sign-on)
      apiKey: '', // Your API key that can be generated or referenced at https://disqus.com/api/applications/
      sso: {
        name: 'SingaRate Community',
        button: `${currentOrigin}/favicon.png`,
        icon: `${currentOrigin}/favicon.png`,
        url: `${currentOrigin}/login/`,
        logout: `${currentOrigin}/logout/`,
        profile_url: `${currentOrigin}/user/{username}`,
        width: '800',
        height: '400',
      },
    };
  }, [article, currentOrigin]);

  const activeConfig = useSsoConfig ? ssoConfig : standardConfig;

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="bg-white rounded-2xl border border-slate-200 p-6 sm:p-8 shadow-xs">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-slate-100">
          <div>
            <div className="flex items-center gap-2 text-rose-600 text-xs font-semibold uppercase tracking-wider mb-1.5">
              <MessageSquare className="w-4 h-4" />
              <span>SingaRate Community Forum</span>
            </div>
            <h2 className="text-2xl font-bold tracking-tight text-slate-900">
              Talk to Us
            </h2>
            <p className="text-sm text-slate-500 mt-1 max-w-2xl leading-relaxed">
              Join the conversation on Singapore foreign exchange rates, money changers, travel budgets, and app feedback powered by Disqus.
            </p>
          </div>

          {/* Comment Count badge powered by disqus-react */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center gap-3">
            <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-lg bg-rose-50 border border-rose-200/80 text-rose-800 text-xs font-semibold shadow-2xs">
              <MessagesSquare className="w-4 h-4 text-rose-600" />
              <CommentCount
                shortname={disqusShortname}
                config={{
                  url: article.url,
                  identifier: article.id,
                  title: article.title,
                }}
              >
                {/* Fallback while loading */}
                <span>Community Comments</span>
              </CommentCount>
            </div>

            {/* SSO Toggle */}
            <button
              type="button"
              onClick={() => setUseSsoConfig(!useSsoConfig)}
              className={`text-xs px-3 py-1.5 rounded-lg border font-medium transition-colors cursor-pointer flex items-center gap-1.5 ${
                useSsoConfig
                  ? 'bg-slate-900 text-white border-slate-900'
                  : 'bg-slate-50 text-slate-600 border-slate-200 hover:bg-slate-100'
              }`}
              title="Toggle Single Sign-On (SSO) Disqus configuration"
            >
              <Shield className="w-3.5 h-3.5 text-rose-400" />
              <span>SSO Config: {useSsoConfig ? 'Enabled' : 'Standard'}</span>
            </button>
          </div>
        </div>

        {/* Channel / Topic Selector */}
        <div className="mt-6">
          <label className="text-xs font-bold text-slate-500 uppercase tracking-wider block mb-3">
            Choose Discussion Topic:
          </label>
          <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
            {topics.map((topic) => {
              const isSelected = selectedTopicId === topic.id;
              return (
                <button
                  key={topic.id}
                  type="button"
                  onClick={() => setSelectedTopicId(topic.id)}
                  className={`p-3.5 rounded-xl border text-left transition-all cursor-pointer flex flex-col justify-between ${
                    isSelected
                      ? 'border-rose-500 bg-rose-50/40 shadow-xs ring-1 ring-rose-500'
                      : 'border-slate-200/90 bg-slate-50/50 hover:bg-white hover:border-slate-300'
                  }`}
                >
                  <div>
                    <div className="flex items-center justify-between">
                      <span className="text-xl select-none">{topic.icon}</span>
                      {isSelected && (
                        <CheckCircle2 className="w-4 h-4 text-rose-600" />
                      )}
                    </div>
                    <div className="font-bold text-xs text-slate-900 mt-2">{topic.title}</div>
                    <div className="text-[11px] text-slate-500 mt-0.5 leading-snug line-clamp-2">
                      {topic.subtitle}
                    </div>
                  </div>

                  <div className="mt-3 pt-2 border-t border-slate-200/60 text-[10px] font-mono text-slate-400">
                    ID: {topic.id}
                  </div>
                </button>
              );
            })}
          </div>
        </div>
      </div>

      {/* Embedded Forum Card */}
      <div className="bg-white rounded-2xl border border-slate-200 p-6 sm:p-8 shadow-xs">
        <div className="mb-6 flex flex-wrap items-center justify-between gap-2 pb-4 border-b border-slate-100">
          <div>
            <h3 className="text-base font-bold text-slate-900 flex items-center gap-2">
              <span>{activeTopic.icon}</span>
              <span>{activeTopic.title}</span>
            </h3>
            <span className="text-xs font-mono text-slate-400 mt-0.5 block">
              Disqus Forum: {disqusShortname} · Thread: {article.id}
            </span>
          </div>

          <div className="flex items-center gap-2 text-xs text-slate-500">
            <span className="inline-block w-2 h-2 rounded-full bg-emerald-500" />
            <span>Forum Active</span>
          </div>
        </div>

        {/* Disqus Embed Container */}
        <div className="min-h-[380px] w-full">
          {/* Key ensures clean re-render when changing active topic or SSO mode */}
          <DiscussionEmbed
            key={`${activeTopic.id}-${useSsoConfig ? 'sso' : 'standard'}`}
            shortname={disqusShortname}
            config={activeConfig}
          />
        </div>

        {/* Helpful note */}
        <div className="mt-8 pt-4 border-t border-slate-100 flex items-start gap-2.5 text-xs text-slate-400">
          <Info className="w-4 h-4 text-slate-400 shrink-0 mt-0.5" />
          <p className="leading-relaxed">
            Disqus comments load directly from <code className="font-mono text-slate-600">{disqusShortname}.disqus.com</code>.
            If comments do not render in private browsing, ensure content blockers allow third-party widgets.
          </p>
        </div>
      </div>
    </div>
  );
}
